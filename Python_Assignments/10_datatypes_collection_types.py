# 5. Data Types - List, Tuple, Set and Dictionary
my_list = [1, 2, 3]
my_tuple = (1, 2, 3)
my_set = {1, 2, 3}
my_dictionary = {"name": "Ruchir", "age": 21}

print("List:", my_list, type(my_list))
print("Tuple:", my_tuple, type(my_tuple))
print("Set:", my_set, type(my_set))
print("Dictionary:", my_dictionary, type(my_dictionary))
