# 2. Data Types - Accept Two Numbers
a = input("Enter first number: ")
b = input("Enter second number: ")

print("First value:", a, "Type:", type(a))
print("Second value:", b, "Type:", type(b))

a = int(a)
b = int(b)

print("After conversion:")
print("First value:", a, "Type:", type(a))
print("Second value:", b, "Type:", type(b))
